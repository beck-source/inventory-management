<template>
  <Teleport to="body">
    <Transition name="modal">
      <div v-if="isOpen && backlogItem" class="modal-overlay" @click="close">
        <div class="modal-container" @click.stop>
          <div class="modal-header">
            <h3 class="modal-title">{{ title }}</h3>
            <button class="close-button" @click="close" aria-label="Close">
              <svg width="20" height="20" viewBox="0 0 20 20" fill="none">
                <path d="M15 5L5 15M5 5L15 15" stroke="currentColor" stroke-width="2" stroke-linecap="round"/>
              </svg>
            </button>
          </div>

          <div class="modal-body">
            <div class="info-grid">
              <div class="info-item">
                <div class="info-label">Item</div>
                <div class="info-value">{{ translateProductName(backlogItem.item_name) }}</div>
              </div>
              <div class="info-item">
                <div class="info-label">SKU</div>
                <div class="info-value sku">{{ backlogItem.item_sku }}</div>
              </div>
              <div class="info-item">
                <div class="info-label">Shortage</div>
                <div class="info-value shortage">{{ shortage }} units</div>
              </div>
            </div>

            <p class="stub-note">
              Purchase order creation is not yet available.
            </p>
          </div>

          <div class="modal-footer">
            <button class="btn-secondary" @click="close">Close</button>
          </div>
        </div>
      </div>
    </Transition>
  </Teleport>
</template>

<script setup>
// STUB: pending /api/purchase-orders endpoints. No backend exists yet, so this
// modal only displays the backlog item and never emits `po-created`.
import { computed } from 'vue'
import { useI18n } from '../composables/useI18n'

const { translateProductName } = useI18n()

const props = defineProps({
  isOpen: {
    type: Boolean,
    default: false
  },
  backlogItem: {
    type: Object,
    default: null
  },
  mode: {
    type: String,
    default: 'create',
    validator: (value) => ['create', 'view'].includes(value)
  }
})

// 'po-created' is declared only so Dashboard's @po-created listener is a known component event
// (otherwise Vue warns about an extraneous listener). The stub never emits it.
const emit = defineEmits(['close', 'po-created'])

const title = computed(() => (props.mode === 'view' ? 'Purchase Order' : 'Create Purchase Order'))

const shortage = computed(() => {
  if (!props.backlogItem) return 0
  return props.backlogItem.quantity_needed - props.backlogItem.quantity_available
})

const close = () => {
  emit('close')
}
</script>

